"""Export a flashcard CSV to Anki, and build a one-page study site.

Inputs (CSV columns): front, back, sources, tags
A card whose front uses Anki cloze markup ({{c1::answer}} or {{c1::answer::hint}})
is a cloze card; its back is optional "extra" text. Every other card is basic.

Outputs, next to the CSV:
  <name>.anki.txt        basic cards  -> Anki: File > Import (note type Basic)
  <name>.cloze.anki.txt  cloze cards  -> Anki: File > Import (note type Cloze), only if any
                         Both go into deck "AI Study::<folder>". Each card has a stable ID
                         from its front, so re-importing an edited deck updates cards.
  <name>.html            self-contained page: study guide + flip cards
  <name>_sources/        with --notes: rendered copies of each cited notes file, so
                         every course citation on the page opens the exact slide

Usage:
    uv run scripts/export.py output/<case>/flashcards.csv \\
        [--guide output/<case>/study-guide.md] [--notes notes/<case>] \\
        [--diagrams output/<case>/diagrams] [--art output/<case>/art] \\
        [--vignettes output/<case>/vignettes.json]

--diagrams adds a "Diagrams" tab: each <slug>.occlusion.json (from occlude.py) shows its card
PNG, title, and labels with linked citations. --art adds a "Memory aids" tab with the PNGs
from mnemonic_art.py, headed "AI illustrations - memory aids, not references". PNGs are copied
to <name>_media/. --vignettes adds a "Vignettes" tab from a vignettes.json
({"vignettes": [{"id", "objective"?, "discipline"?, "stem", "options": [{"key", "text", "correct",
"explanation"}]}]}): each case shows its stem and a textarea; "Show options" stays disabled until
something is typed, and the options live only in an inert <template> until then. Picking an option
reveals every explanation (citations linked like card citations) and marks right/wrong. Typed text
and score stay in the page: no storage, no network. A malformed file exits with a readable message.
Without any of these flags the page is unchanged.
"""

from __future__ import annotations

import argparse
import csv
import hashlib
import html
import json
import re
import shutil
import urllib.parse
from pathlib import Path

import markdown

PMID = re.compile(r"\[?PMID:\s*(\d{4,9})\]?")  # any whitespace, incl. a CRLF line break
COURSE = re.compile(r"\[\[([^\]#]+)#([SPT]\d+)\]\]")
CLOZE = re.compile(r"\{\{c(\d+)::(.*?)(?:::(.*?))?\}\}", re.S)
ANCHORED_HEADING = re.compile(r"^(#{1,6})\s*\[([SPT]\d+)\]\s*(.*)$")
ANCHORED_LINE = re.compile(r"^\[([SPT]\d+)\]\s*(.*)$")
MARKER = ".generated-by-export"
BANNER = "Course material from your school — for your own study, do not share."


def guid(front: str) -> str:
    return "msad-" + hashlib.sha1(front.strip().lower().encode()).hexdigest()[:12]


def is_cloze(front: str) -> bool:
    return bool(CLOZE.search(front or ""))


class SourceLinker:
    """Renders cited notes files into <name>_sources/ and returns relative links to their anchors."""

    def __init__(self, notes_dir: Path, page: Path):
        self.notes = notes_dir.resolve()
        self.folder_name = f"{page.stem}_sources"
        self.out = (page.parent / self.folder_name).resolve()
        if self.out.exists():
            if not (self.out / MARKER).is_file():
                raise SystemExit(f"refusing to replace {self.out}: it was not created by export.py (no {MARKER} file)")
            shutil.rmtree(self.out)  # our own generated folder; rebuilt every run
        self.rendered: dict[str, set[str]] = {}
        self.warnings: list[str] = []

    def _warn(self, msg: str) -> None:
        if msg not in self.warnings:
            self.warnings.append(msg)

    def href(self, rel: str, anchor: str) -> str | None:
        rel = rel.strip()
        src = (self.notes / f"{rel}.md").resolve()
        dest = (self.out / f"{rel}.html").resolve()
        if not src.is_relative_to(self.notes) or not dest.is_relative_to(self.out):
            self._warn(f"warning: citation [[{rel}#{anchor}]] points outside the notes folder; left as a label")
            return None
        if not src.is_file():
            self._warn(f"warning: no notes file for [[{rel}#{anchor}]]; left as a label")
            return None
        if rel not in self.rendered:
            self.out.mkdir(parents=True, exist_ok=True)
            (self.out / MARKER).write_text("Generated by scripts/export.py; safe to delete.\n", encoding="utf-8")
            self.rendered[rel] = self._render(src, dest, rel)
        if anchor not in self.rendered[rel]:
            self._warn(f"warning: {anchor} is not a slide/paragraph/table marker in {rel}; left as a label")
            return None
        path = "/".join(urllib.parse.quote(part) for part in rel.split("/"))
        return f"{self.folder_name}/{path}.html#{anchor}"

    @staticmethod
    def _render(src: Path, dest: Path, rel: str) -> set[str]:
        ids: set[str] = set()
        parts: list[str] = []
        plain: list[str] = []

        md = markdown.Markdown(extensions=["tables"])

        def flush() -> None:
            if plain:
                parts.append(md.convert("\n".join(plain)))
                md.reset()
                plain.clear()

        for line in src.read_text(encoding="utf-8").splitlines():
            if m := ANCHORED_HEADING.match(line):
                flush()
                level, aid, rest = len(m.group(1)), m.group(2), m.group(3)
                ids.add(aid)
                parts.append(f'<h{level} id="{aid}"><span class="tag">[{aid}]</span> {html.escape(rest)}</h{level}>')
            elif m := ANCHORED_LINE.match(line):
                flush()
                aid, rest = m.group(1), m.group(2)
                ids.add(aid)
                parts.append(f'<p id="{aid}"><span class="tag">[{aid}]</span> {html.escape(rest)}</p>')
            else:
                plain.append(re.sub(r"<(?=[A-Za-z/!?])", "&lt;", line))  # notes text is data, never markup
        flush()
        dest.parent.mkdir(parents=True, exist_ok=True)
        page = SOURCE_TEMPLATE.replace("__TITLE__", html.escape(rel)).replace("__BODY__", "\n".join(parts))
        dest.write_text(page, encoding="utf-8")
        return ids


def linkify(text: str, linker: SourceLinker | None = None) -> str:
    """Turn citations into links. Course citations link only when a linker is given."""
    text = PMID.sub(r'<a class="cite" href="https://pubmed.ncbi.nlm.nih.gov/\1/">PMID \1</a>', text)

    def course(m: re.Match) -> str:
        rel, anchor = m.group(1), m.group(2)
        label = f"{html.escape(rel)} · {anchor}"
        href = linker.href(html.unescape(rel), anchor) if linker else None
        if href:
            return f'<a class="cite course" href="{html.escape(href)}" target="_blank" title="Open the cited source">{label}</a>'
        return f'<span class="cite course" title="{html.escape(rel)}">{label}</span>'

    return COURSE.sub(course, text)


ART_HEADING = "AI illustrations — memory aids, not references"


def _media_src(src: Path, kind: str, page: Path) -> str | None:
    """Copy a PNG next to the page under <name>_media/<kind>/ and return its relative URL.

    Only files export.py created (listed in the folder's marker) or byte-identical files are replaced;
    any other existing file is left alone with a warning and None is returned.
    """
    folder = f"{page.stem}_media"
    root = page.parent / folder
    rel = f"{kind}/{src.name}"
    dest = root / rel
    marker = root / MARKER
    owned = set(marker.read_text(encoding="utf-8").splitlines()) if marker.is_file() else set()
    if dest.exists() and rel not in owned and dest.read_bytes() != src.read_bytes():
        print(f"warning: {dest} already exists and was not created by export.py; left untouched, {src.name} skipped")
        return None
    dest.parent.mkdir(parents=True, exist_ok=True)
    shutil.copyfile(src, dest)
    if rel not in owned:
        owned.add(rel)
        marker.write_text("\n".join(sorted(owned)) + "\n", encoding="utf-8")
    return f"{folder}/{kind}/{urllib.parse.quote(src.name)}"


def _folder(path: Path, flag: str) -> Path:
    if not path.is_dir():
        raise SystemExit(f"{flag}: {path} is not a folder")
    return path


def diagrams_section(folder: Path, page: Path, linker: SourceLinker | None) -> str:
    """HTML for the Diagrams tab: the card PNG (never the SVG/HTML) and its cited labels."""
    folder = _folder(folder, "--diagrams").resolve()
    blocks = []
    for spec_path in sorted(folder.glob("*.occlusion.json")):
        spec = json.loads(spec_path.read_text(encoding="utf-8"))
        png = (folder / str(spec.get("image", ""))).resolve()
        if png.suffix.lower() != ".png" or not png.is_file() or not png.is_relative_to(folder):
            print(f"warning: {spec_path.name}: card image missing; diagram skipped")
            continue
        url = _media_src(png, "diagrams", page)
        if url is None:
            continue
        title = html.escape(str(spec.get("title") or spec.get("slug") or png.stem))
        items = "".join(
            f"<li>{html.escape(str(lab.get('label', '')))} "
            f"<small>{linkify(html.escape(str(lab.get('cite', ''))), linker)}</small></li>"
            for lab in spec.get("labels", [])
        )
        blocks.append(
            f'<figure class="dg"><h2>{title}</h2>'
            f'<img class="diagram" src="{html.escape(url)}" alt="{title}">'
            f"<ul>{items}</ul></figure>"
        )
    return "\n".join(blocks)


def art_section(folder: Path, page: Path) -> str:
    """HTML for the Memory aids tab: every PNG under a heading that says it is not a reference."""
    folder = _folder(folder, "--art").resolve()
    blocks = []
    for png in sorted(folder.glob("*.png")):
        url = _media_src(png, "art", page)
        if url is None:
            continue
        caption = png.stem.replace("-", " ").replace("_", " ")
        sidecar = png.with_suffix(".json")
        if sidecar.is_file():
            try:
                caption = str(json.loads(sidecar.read_text(encoding="utf-8")).get("caption") or caption)
            except (ValueError, AttributeError):
                pass
        cap = html.escape(caption)
        blocks.append(
            f'<figure class="aid"><img class="art" src="{html.escape(url)}" alt="{cap}">'
            f"<figcaption>{cap}</figcaption></figure>"
        )
    if not blocks:
        return ""
    return f"<h2>{ART_HEADING}</h2>\n" + "\n".join(blocks)


def load_vignettes(path: Path) -> list[dict]:
    """Read and shape-check a vignettes file; any problem is a one-line SystemExit, never a traceback."""
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError) as exc:
        raise SystemExit(f"--vignettes: cannot read {path}: {exc}")
    items = data.get("vignettes") if isinstance(data, dict) else None
    if not isinstance(items, list):
        raise SystemExit(f'--vignettes: {path} must be an object with a "vignettes" list')
    for n, v in enumerate(items, 1):
        opts = v.get("options") if isinstance(v, dict) else None
        if (
            not isinstance(v, dict)
            or not isinstance(v.get("stem"), str)
            or not isinstance(opts, list)
            or not opts
            or not all(isinstance(o, dict) and isinstance(o.get("text"), str) for o in opts)
        ):
            raise SystemExit(f'--vignettes: vignette #{n} needs a "stem" string and a non-empty "options" list of objects with "text"')
    return items


def vignettes_section(path: Path, linker: SourceLinker | None) -> str:
    """HTML for the Vignettes tab. Options (and their explanations) exist only inside an inert <template>."""
    blocks = []
    for n, v in enumerate(load_vignettes(path), 1):
        rows = []
        for o in v["options"]:
            key = html.escape(str(o.get("key", "")))
            expl = linkify(html.escape(str(o.get("explanation", "")), quote=False), linker)
            rows.append(
                f'<li><button type="button" class="vopt" data-correct="{"1" if o.get("correct") is True else "0"}">'
                f'<b>{key}.</b> {html.escape(o["text"], quote=False)}</button>'
                f'<div class="vexp" hidden><span class="vmark"></span> {expl}</div></li>'
            )
        label = html.escape(str(v.get("discipline") or ""))
        blocks.append(
            f'<article class="vg"><h2>Case {n}</h2>'
            + (f"<small>{label}</small>" if label else "")
            + f'<p class="vstem">{html.escape(str(v["stem"]), quote=False)}</p>'
            f'<label>Your answer and reasoning<br><textarea class="vans" rows="3"></textarea></label>'
            f'<div class="row"><button type="button" class="vshow" disabled>Show options</button></div>'
            f'<ol class="vlist" type="A"></ol><template class="vtpl">{"".join(rows)}</template></article>'
        )
    return "\n".join(blocks)


