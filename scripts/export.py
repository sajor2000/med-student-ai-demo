def cloze_front(text: str) -> str:
    return CLOZE.sub(lambda m: f'<span class="cz">[{m.group(3) or "…"}]</span>', text)


def cloze_reveal(text: str) -> str:
    return CLOZE.sub(lambda m: f"<mark>{m.group(2)}</mark>", text)


def anki_breaks(field: str) -> str:
    """Line breaks become <br> (Anki clozes break on raw newlines). Run after linkify, so citations split across lines still link."""
    return field.replace("\r\n", "\n").replace("\n", "<br>")


def anki_html(text: str) -> str:
    """Escape plain card text for an HTML Anki field."""
    return anki_breaks(html.escape(text, quote=False))


def write_anki(path: Path, cards: list[dict], notetype: str, deck: str) -> None:
    with path.open("w", newline="", encoding="utf-8") as out:
        out.write(f"#separator:tab\n#html:true\n#notetype:{notetype}\n#deck:{deck}\n#guid column:1\n#tags column:4\n")
        writer = csv.writer(out, delimiter="\t", lineterminator="\n", quoting=csv.QUOTE_MINIMAL)
        for c in cards:
            extra = anki_breaks(linkify(html.escape(c["back"], quote=False)))
            sources = "<small>" + anki_breaks(linkify(html.escape(c["sources"], quote=False))) + "</small>"
            back = f"{extra}<br>{sources}" if extra else sources
            tags = " ".join(t.strip().replace(" ", "_") for t in c.get("tags", "").split(";") if t.strip())
            # csv quoting keeps a tab or newline inside a field from splitting the Anki record
            writer.writerow([guid(c["front"]), anki_html(c["front"]), back, tags])


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("csv", type=Path)
    ap.add_argument("--guide", type=Path, help="study guide Markdown to include on the page")
    ap.add_argument("--notes", type=Path, help="notes folder from extract.py; makes course citations clickable")
    ap.add_argument("--diagrams", type=Path, help="folder of <slug>.occlusion.json + card PNGs; adds a Diagrams tab")
    ap.add_argument("--art", type=Path, help="folder of mnemonic-art PNGs; adds a Memory aids tab")
    ap.add_argument("--vignettes", type=Path, help="vignettes.json; adds a Vignettes tab (options hidden until an answer is typed)")
    args = ap.parse_args()

    with args.csv.open(newline="", encoding="utf-8") as fh:
        cards = list(csv.DictReader(fh))

    seen: set[str] = set()
    for c in cards:
        g = guid(c["front"])
        if g in seen:
            print(f"warning: duplicate card front (same Anki ID): {c['front'][:60]!r}")
        seen.add(g)

    deck = "AI Study::" + (args.csv.parent.name or "deck")
    flags = [is_cloze(c["front"]) for c in cards]
    basic = [c for c, cz in zip(cards, flags) if not cz]
    cloze = [c for c, cz in zip(cards, flags) if cz]
    anki = args.csv.with_suffix(".anki.txt")
    cloze_file = args.csv.with_suffix(".cloze.anki.txt")
    write_anki(anki, basic, "Basic", deck)
    if cloze:
        write_anki(cloze_file, cloze, "Cloze", deck)
    elif cloze_file.exists():
        cloze_file.unlink()

    site = args.csv.with_suffix(".html")
    linker = SourceLinker(args.notes, site) if args.notes else None

    guide_html = ""
    if args.guide and args.guide.exists():
        guide_html = linkify(markdown.markdown(args.guide.read_text(encoding="utf-8"), extensions=["tables"]), linker)

    data = []
    for c, cz in zip(cards, flags):
        front = html.escape(c["front"])
        item = {
            "front": cloze_front(front) if cz else front,
            "back": linkify(html.escape(c["back"], quote=False), linker),
            "sources": linkify(html.escape(c["sources"], quote=False), linker),
            "tags": c.get("tags", ""),
            "cloze": cz,
        }
        if cz:
            item["reveal"] = cloze_reveal(front)
        data.append(item)
    page = TEMPLATE.replace("__TITLE__", html.escape(args.csv.stem.replace("-", " ").title()))
    page = page.replace("__GUIDE__", guide_html or "<p>No study guide passed (use --guide).</p>")
    page = page.replace("__CARDS__", json.dumps(data))
    extras = []  # (button id, label, section id, inner html) for the optional tabs
    if args.diagrams and (inner := diagrams_section(args.diagrams, site, linker)):
        extras.append(("td", "Diagrams", "diagrams", inner))
    if args.art and (inner := art_section(args.art, site)):
        extras.append(("ta", "Memory aids", "art", inner))
    if args.vignettes and (inner := vignettes_section(args.vignettes, linker)):
        extras.append(("tv", "Vignettes", "vignettes", inner))
    if extras:
        buttons = "".join(f'<button id="{b}" aria-pressed="false">{label}</button>' for b, label, _, _ in extras)
        sections = "".join(f'<section id="{sid}" hidden>{inner}</section>\n' for _, _, sid, inner in extras)
        for anchor, spliced in (
            ("</nav>", buttons + "</nav>"),
            ("</main><script>", sections + "</main><script>"),
            ("</style>", EXTRA_CSS + "</style>"),
            ("</script></body></html>", "</script>" + EXTRA_JS + "</body></html>"),
        ):
            if anchor not in page:
                raise RuntimeError(f"export template is missing the anchor {anchor!r}; extra tabs cannot be added")
            page = page.replace(anchor, spliced, 1)
        if any(e[0] == "tv" for e in extras):
            page = page.replace("['ta','art']]", "['ta','art'],['tv','vignettes']]", 1)
            page = page.replace("</style>", VIGNETTE_CSS + "</style>", 1)
            page = page.replace("</body></html>", VIGNETTE_JS + "</body></html>", 1)
    site.write_text(page, encoding="utf-8")

    print(f"{len(basic)} basic cards -> {anki} (Anki: File > Import)")
    if cloze:
        print(f"{len(cloze)} cloze cards -> {cloze_file} (Anki: File > Import)")
    print(f"study site  -> {site}")
    if linker:
        for w in linker.warnings:
            print(w)
        if linker.rendered:
            print(f"sources     -> {linker.out} ({len(linker.rendered)} files). {BANNER}")
    return 0


